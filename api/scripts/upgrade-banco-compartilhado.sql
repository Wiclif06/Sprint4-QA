-- Sprint 3: extensão aditiva para o banco do anexo Banco PetJourney.
-- Executar no schema que já contém TBTUTOR, TBCLINICA e TBPET.
-- Não execute as migrações de criação da API em um schema criado pelo script de Banco.
WHENEVER SQLERROR EXIT SQL.SQLCODE
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE PJTUTORCLINICA (
    IDTUTOR NUMBER(10) NOT NULL,
    IDCLINICA NUMBER(10) NOT NULL,
    CONSTRAINT PK_PJTUTORCLINICA PRIMARY KEY (IDTUTOR, IDCLINICA),
    CONSTRAINT FK_PJTC_TUTOR FOREIGN KEY (IDTUTOR) REFERENCES TBTUTOR(IDTUTOR),
    CONSTRAINT FK_PJTC_CLINICA FOREIGN KEY (IDCLINICA) REFERENCES TBCLINICA(IDCLINICA))';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
MERGE INTO PJTUTORCLINICA target
USING (SELECT DISTINCT IDTUTOR, IDCLINICA FROM TBPET WHERE IDCLINICA IS NOT NULL) source
ON (target.IDTUTOR = source.IDTUTOR AND target.IDCLINICA = source.IDCLINICA)
WHEN NOT MATCHED THEN INSERT (IDTUTOR, IDCLINICA) VALUES (source.IDTUTOR, source.IDCLINICA);
COMMIT;
SELECT IDTUTOR, IDCLINICA FROM PJTUTORCLINICA ORDER BY IDTUTOR, IDCLINICA;
