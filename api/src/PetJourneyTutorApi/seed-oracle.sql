-- Dados de demonstração exclusivos do schema criado pelas migrações desta API.
-- Não apaga registros; exige as tabelas principais vazias. Não usar no schema compartilhado do anexo Banco.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
  quantidade NUMBER;
  cachorro NUMBER; gato NUMBER; raca NUMBER;
  clinica1 NUMBER; clinica2 NUMBER; tutor1 NUMBER; tutor2 NUMBER; pet1 NUMBER; pet2 NUMBER;
BEGIN
  SELECT (SELECT COUNT(*) FROM TBPET)+(SELECT COUNT(*) FROM TBTUTOR)+
         (SELECT COUNT(*) FROM TBCLINICA)+(SELECT COUNT(*) FROM TBESPECIE)+
         (SELECT COUNT(*) FROM TBRACA)+(SELECT COUNT(*) FROM TBLEMBRETE)
    INTO quantidade FROM DUAL;
  IF quantidade > 0 THEN RAISE_APPLICATION_ERROR(-20001,'Seed permitido apenas em schema da API vazio.'); END IF;
  INSERT INTO TBESPECIE(NMESPECIE) VALUES('Cachorro') RETURNING IDESPECIE INTO cachorro;
  INSERT INTO TBESPECIE(NMESPECIE) VALUES('Gato') RETURNING IDESPECIE INTO gato;
  INSERT INTO TBRACA(NMRACA,IDESPECIE) VALUES('Golden Retriever',cachorro) RETURNING IDRACA INTO raca;
  INSERT INTO TBCLINICA(NMCLINICA,DSEMAIL,DSSTATUS) VALUES('Pet Feliz','contato@petfeliz.test','ATIVA') RETURNING IDCLINICA INTO clinica1;
  INSERT INTO TBCLINICA(NMCLINICA,DSEMAIL,DSSTATUS) VALUES('Saúde Animal','contato@saudeanimal.test','ATIVA') RETURNING IDCLINICA INTO clinica2;
  INSERT INTO TBTUTOR(NMTUTOR,DSEMAIL,NRTELEFONE) VALUES('Carlos','carlos@petjourney.com','11911112222') RETURNING IDTUTOR INTO tutor1;
  INSERT INTO TBTUTOR(NMTUTOR,DSEMAIL,NRTELEFONE) VALUES('Ana','ana@petjourney.com','11933334444') RETURNING IDTUTOR INTO tutor2;
  INSERT INTO PJTUTORCLINICA(IDTUTOR,IDCLINICA) VALUES(tutor1,clinica1);
  INSERT INTO PJTUTORCLINICA(IDTUTOR,IDCLINICA) VALUES(tutor2,clinica2);
  INSERT INTO TBPET(NMPET,DSSEXO,IDTUTOR,IDESPECIE,IDRACA,IDCLINICA) VALUES('Rex','M',tutor1,cachorro,raca,clinica1) RETURNING IDPET INTO pet1;
  INSERT INTO TBPET(NMPET,DSSEXO,IDTUTOR,IDESPECIE,IDCLINICA) VALUES('Mia','F',tutor2,gato,clinica2) RETURNING IDPET INTO pet2;
  INSERT INTO TBLEMBRETE(IDPET,DSTIPO,DSDESCRICAO,DTLEMBRETE) VALUES(pet1,'VACINA','Vacinação Rex',TRUNC(SYSDATE)+2);
  INSERT INTO TBLEMBRETE(IDPET,DSTIPO,DSDESCRICAO,DTLEMBRETE) VALUES(pet2,'RETORNO','Retorno Mia',TRUNC(SYSDATE)+3);
  COMMIT;
END;
/
-- Usar os IDs retornados abaixo no provisionamento das contas; não presumir sequências em 1.
SELECT IDTUTOR,NMTUTOR,DSEMAIL FROM TBTUTOR ORDER BY IDTUTOR;
SELECT IDCLINICA,NMCLINICA FROM TBCLINICA ORDER BY IDCLINICA;
SELECT IDPET,NMPET,IDTUTOR,IDCLINICA FROM TBPET ORDER BY IDPET;
